export const properties = raw.map((property) => ({
  ...property,
  images: property.images.map((id) => shot(id)),
}))

export const places = [
  ...new Set(
    properties.flatMap((property) => [
      property.city,
      property.neighborhood,
      `${property.neighborhood}, ${property.city}`,
    ]),
  ),
].sort()

export function getProperty(id) {
  return properties.find((property) => property.id === id)
}

export function relatedProperties(property, count = 3) {
  const sameCity = properties.filter(
    (item) => item.id !== property.id && item.city === property.city,
  )
  const sameType = properties.filter(
    (item) => item.id !== property.id && item.type === property.type && item.city !== property.city,
  )
  const rest = properties.filter((item) => item.id !== property.id)
  const merged = [...sameCity, ...sameType, ...rest]
  const unique = []
  merged.forEach((item) => {
    if (!unique.some((picked) => picked.id === item.id)) unique.push(item)
  })
  return unique.slice(0, count)
}
